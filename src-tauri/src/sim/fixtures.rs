//! What the simulated printers hold, made at launch: sample G-codes shaped
//! like Snapmaker Orca's (header, thumbnail, layers, tool changes, the
//! consumption at the end), the timelapse videos' small MP4, and the U1's
//! configuration (`src-tauri/sim/fixtures/`).

use super::scenario::{SampleFile, Spool};
use std::fmt::Write;

pub const CONFIG_SETTINGS: &str = include_str!("../../sim/fixtures/configfile_settings.json");
pub const FILAMENT_PARAMETERS: &str = include_str!("../../sim/fixtures/filament_parameters.json");

/// `configfile.settings`, parsed once.
pub fn settings() -> &'static serde_json::Value {
    static S: std::sync::OnceLock<serde_json::Value> = std::sync::OnceLock::new();
    S.get_or_init(|| serde_json::from_str(CONFIG_SETTINGS).expect("configfile_settings.json"))
}

fn hms(secs: u32) -> String {
    let (h, m, s) = (secs / 3600, secs / 60 % 60, secs % 60);
    if h > 0 {
        format!("{h}h {m}m {s}s")
    } else {
        format!("{m}m {s}s")
    }
}

/// A flat picture of the part in its first colour: the G-code's thumbnail.
fn thumbnail(color: [u8; 3], size: u32) -> Vec<u8> {
    let mut img = image::RgbaImage::new(size, size);
    let (a, b) = (size / 5, size * 4 / 5);
    for (x, y, p) in img.enumerate_pixels_mut() {
        let inside = x >= a && x < b && y >= a && y < b;
        let edge = inside && (x < a + 3 || x >= b - 3 || y < a + 3 || y >= b - 3);
        *p = if edge {
            image::Rgba([color[0] / 2, color[1] / 2, color[2] / 2, 255])
        } else if inside {
            image::Rgba([color[0], color[1], color[2], 255])
        } else {
            image::Rgba([0, 0, 0, 0])
        };
    }
    let mut out = std::io::Cursor::new(Vec::new());
    let _ = img.write_to(&mut out, image::ImageFormat::Png);
    out.into_inner()
}

pub fn rgb(hex: &str) -> [u8; 3] {
    let h = hex.trim().trim_start_matches('#');
    let v = h.get(..6).and_then(|h| u32::from_str_radix(h, 16).ok()).unwrap_or(0x808080);
    [(v >> 16) as u8, (v >> 8) as u8, v as u8]
}

/// A sample print file: a square part, each layer printed by each of its
/// tools in turn, with the comments `gcode.rs` and Moonraker read.
pub fn sample_gcode(f: &SampleFile, spools: &[Spool]) -> String {
    let tools: Vec<u8> = if f.tools.is_empty() { vec![0] } else { f.tools.clone() };
    let max_tool = *tools.iter().max().unwrap_or(&0) as usize;
    let n = max_tool + 1;
    let pick = |list: &[String], i: usize, fallback: String| list.get(i).cloned().filter(|s| !s.is_empty()).unwrap_or(fallback);
    // Per tool index: the file's own, else the loaded spool's.
    let materials: Vec<String> = (0..n)
        .map(|t| {
            let k = tools.iter().position(|x| *x as usize == t);
            let own = k.and_then(|k| f.materials.get(k).cloned());
            own.or_else(|| spools.get(t).map(|s| s.kind.clone())).filter(|s| !s.is_empty()).unwrap_or_else(|| "PLA".into())
        })
        .collect();
    let colors: Vec<String> = (0..n)
        .map(|t| {
            let k = tools.iter().position(|x| *x as usize == t);
            let own = k.and_then(|k| f.colors.get(k).cloned());
            own.or_else(|| spools.get(t).map(|s| s.color.clone())).unwrap_or_else(|| pick(&[], 0, "#808080".into()))
        })
        .collect();
    let total = f.minutes.max(1) * 60;
    let layers = f.layers.max(2);
    let lh = 0.2f32;
    // Each used tool's filament, mm: proportional to its share of the paths.
    let per_layer_mm = 120.0f32;
    let mut used_mm = vec![0f32; n];
    for t in &tools {
        used_mm[*t as usize] = per_layer_mm * layers as f32;
    }
    let grams: Vec<f32> = used_mm.iter().map(|mm| mm * 0.00298).collect();

    let mut g = String::with_capacity(64 * 1024);
    let _ = writeln!(g, "; HEADER_BLOCK_START");
    let _ = writeln!(g, "; generated by Snap Studio simulator");
    let _ = writeln!(g, "; model printing time: {}; total estimated time: {}", hms(total.saturating_sub(90)), hms(total));
    let _ = writeln!(g, "; total layer number: {layers}");
    let _ = writeln!(g, "; HEADER_BLOCK_END");
    let png = thumbnail(rgb(&colors[tools[0] as usize]), 300);
    let b64 = crate::util::b64_encode(&png);
    let _ = writeln!(g, ";\n; THUMBNAIL_BLOCK_START\n; thumbnail begin 300x300 {}", b64.len());
    for chunk in b64.as_bytes().chunks(78) {
        let _ = writeln!(g, "; {}", String::from_utf8_lossy(chunk));
    }
    let _ = writeln!(g, "; thumbnail end\n; THUMBNAIL_BLOCK_END\n;");
    let _ = writeln!(g, "; CONFIG_BLOCK_START");
    let _ = writeln!(g, "; printer_model = Snapmaker U1");
    let _ = writeln!(g, "; layer_height = {lh}");
    let _ = writeln!(g, "; first_layer_bed_temperature = {}", if materials.iter().any(|m| m.contains("PETG")) { 70 } else { 60 });
    let _ = writeln!(
        g,
        "; nozzle_temperature = {}",
        materials.iter().map(|m| if m.contains("PETG") { "240" } else { "220" }).collect::<Vec<_>>().join(",")
    );
    let _ = writeln!(g, "; filament_type = {}", materials.join(";"));
    let _ = writeln!(g, "; filament_colour = {}", colors.join(";"));
    let _ = writeln!(g, "; CONFIG_BLOCK_END");
    let _ = writeln!(g, "; EXECUTABLE_BLOCK_START\nG90\nM83\nM140 S60\nM104 S220\nG28\nT{}", tools[0]);

    let (cx, cy) = (135.0f32, 135.0f32);
    for layer in 0..layers {
        let z = lh * (layer + 1) as f32;
        let _ = writeln!(g, ";LAYER_CHANGE\n;Z:{z:.2}\nG1 Z{z:.2} F600");
        for (k, t) in tools.iter().enumerate() {
            if tools.len() > 1 || layer == 0 {
                let _ = writeln!(g, "T{t}");
            }
            // Each tool its own ring: the part reads as colour bands.
            let r = 18.0 - 4.0 * k as f32;
            let _ = writeln!(g, ";TYPE:Outer wall\n;WIDTH:0.42\nG1 X{:.2} Y{:.2} F12000", cx - r, cy - r);
            for (x, y) in [(cx + r, cy - r), (cx + r, cy + r), (cx - r, cy + r), (cx - r, cy - r)] {
                let _ = writeln!(g, "G1 X{x:.2} Y{y:.2} E{:.4} F3000", r * 2.0 * 0.0333);
            }
            let _ = writeln!(g, ";TYPE:Sparse infill");
            for i in 0..4 {
                let y = cy - r + 4.0 + i as f32 * (r * 2.0 - 8.0) / 3.0;
                let _ = writeln!(
                    g,
                    "G1 X{:.2} Y{y:.2} F12000\nG1 X{:.2} Y{y:.2} E{:.4} F6000",
                    cx - r + 2.0,
                    cx + r - 2.0,
                    (r * 2.0 - 4.0) * 0.0333
                );
            }
        }
    }
    let _ = writeln!(g, "; EXECUTABLE_BLOCK_END\nM140 S0\nM104 S0\nM84");
    let list = |v: &[f32], digits: usize| v.iter().map(|x| format!("{x:.digits$}")).collect::<Vec<_>>().join(", ");
    let _ = writeln!(g, "; filament used [mm] = {}", list(&used_mm, 2));
    let _ = writeln!(g, "; filament used [g] = {}", list(&grams, 2));
    let _ = writeln!(g, "; total filament used [g] = {:.2}", grams.iter().sum::<f32>());
    let _ = writeln!(g, "; estimated printing time (normal mode) = {}", hms(total));
    g
}

/// A small MP4 whose `moov` says it lasts `secs`: what the Printer files
/// view reads (duration, picture). It holds no frames.
pub fn timelapse_mp4(secs: f64) -> Vec<u8> {
    fn bx(kind: &[u8; 4], body: &[u8]) -> Vec<u8> {
        let mut v = ((body.len() + 8) as u32).to_be_bytes().to_vec();
        v.extend_from_slice(kind);
        v.extend_from_slice(body);
        v
    }
    let mut mvhd = vec![0u8; 4];
    mvhd.extend_from_slice(&0u32.to_be_bytes());
    mvhd.extend_from_slice(&0u32.to_be_bytes());
    mvhd.extend_from_slice(&1000u32.to_be_bytes());
    mvhd.extend_from_slice(&((secs * 1000.0) as u32).to_be_bytes());
    mvhd.extend_from_slice(&[0u8; 80]);
    [bx(b"ftyp", b"isom\0\0\x02\0isomiso2mp41"), bx(b"free", &[0u8; 64]), bx(b"moov", &bx(b"mvhd", &mvhd))].concat()
}

/// `YYYYMMDDHHMMSS` of a Unix time (UTC), as the U1 names its timelapses.
pub fn date_index(unix: f64) -> String {
    let secs = unix.max(0.0) as i64;
    let (days, rem) = (secs.div_euclid(86_400), secs.rem_euclid(86_400));
    // Howard Hinnant's civil_from_days.
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z - era * 146_097;
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let d = doy - (153 * mp + 2) / 5 + 1;
    let m = if mp < 10 { mp + 3 } else { mp - 9 };
    let y = yoe + era * 400 + i64::from(m <= 2);
    format!("{y:04}{m:02}{d:02}{:02}{:02}{:02}", rem / 3600, rem / 60 % 60, rem % 60)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sim::scenario::default_spools;

    #[test]
    fn a_sample_reads_like_a_sliced_file() {
        let f = SampleFile { name: "x.gcode".into(), tools: vec![0, 2], minutes: 30, layers: 12, materials: vec![], colors: vec![] };
        let text = sample_gcode(&f, &default_spools());
        let d = crate::gcode::parse(text.as_bytes()).unwrap();
        let st = crate::gcode::stats(&d);
        assert_eq!(st.print_time_s, Some(1800));
        assert_eq!(st.layers, 12 + 1, "the start G-code counts as layer 0");
        assert_eq!(st.tools, vec![0, 2]);
        assert_eq!(st.filament_types, vec!["PLA", "PLA", "PLA"]);
        assert_eq!(st.filament_colors[2], "#d93a2b");
        assert!(st.layer_end_s.last().is_some_and(|t| (t - 1800.0).abs() < 1.0), "{:?}", st.layer_end_s.last());
        assert_eq!(st.per_tool_m.len(), 3);
        assert!(crate::gcode::embedded_thumbnail(text.as_bytes()).is_some_and(|p| p.starts_with(b"\x89PNG")));
        // Its own materials win over the spools'.
        let f = SampleFile { materials: vec!["PETG".into()], colors: vec!["#00ff00".into()], tools: vec![1], ..f };
        let st = crate::gcode::stats(&crate::gcode::parse(sample_gcode(&f, &default_spools()).as_bytes()).unwrap());
        assert_eq!((st.filament_types[1].as_str(), st.filament_colors[1].as_str()), ("PETG", "#00ff00"));
    }

    #[test]
    fn timelapse_names_and_videos() {
        assert_eq!(date_index(0.0), "19700101000000");
        assert_eq!(date_index(1_760_887_800.0), "20251019153000");
        let mp4 = timelapse_mp4(42.5);
        let moov = &mp4[mp4.len() - 116..];
        assert_eq!(crate::printer_files::mvhd_duration(moov), Some(42.5));
    }
}
